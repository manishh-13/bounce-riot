import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const base = process.env.BOUNCE_BASE_URL || 'https://manishh-13.github.io/bounce-riot/';
const artifacts = new URL('../.artifacts/live/', import.meta.url).pathname;
await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined), args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-gpu-sandbox','--disable-background-timer-throttling','--disable-renderer-backgrounding'] });
const errors=[];
let host, phone, context;
try {
  host = await browser.newPage({viewport:{width:1280,height:720}});
  await host.addInitScript(()=>localStorage.setItem('bounce-riot-quality',JSON.stringify('low')));
  host.on('pageerror', e=>errors.push(e.message));
  await host.goto(base);
  await host.locator('#host-button').click();
  await host.waitForFunction(()=>/^[A-Z0-9]{6}$/.test(document.querySelector('#room-code-display')?.textContent??''),null,{timeout:25000});
  const code=await host.locator('#room-code-display').textContent();
  await host.locator('#duration-select').selectOption('30');
  await host.locator('#add-bot').click();
  context = await browser.newContext({viewport:{width:844,height:390},isMobile:true,hasTouch:true});
  phone=await context.newPage();phone.on('pageerror',e=>errors.push(e.message));
  const url=new URL(base);url.hash=`join/${code}`;
  await phone.goto(url.href);
  await phone.locator('#player-name').fill('Live check');
  await phone.locator('#join-button').click();
  await phone.locator('#arm-controller').waitFor({state:'visible',timeout:25000});
  await phone.locator('#arm-controller').click();
  await phone.locator('#controller-gate').waitFor({state:'hidden'});
  await phone.waitForFunction(()=>document.querySelector('#controller-connection')?.textContent==='DIRECT TO TV',null,{timeout:25000});
  await host.screenshot({path:`${artifacts}public-lobby.png`});
  await phone.screenshot({path:`${artifacts}public-controller.png`});
  await phone.locator('#captain-action').click();
  await phone.waitForFunction(()=>document.querySelector('#controller-phase')?.textContent==='BOUNCE RIOT',null,{timeout:30000});
  const cdp=await context.newCDPSession(phone);
  const button=await phone.locator('#slam-button').boundingBox();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:button.x+button.width/2,y:button.y+button.height/2,id:1}]});
  await phone.waitForFunction(()=>document.querySelector('#slam-word')?.textContent==='LET GO!',null,{timeout:10000});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await host.screenshot({path:`${artifacts}public-gameplay.png`});
  await host.locator('#result-panel').waitFor({state:'visible',timeout:90000});
  assert.equal(await host.locator('#results-list li').count(),2);
  await phone.waitForFunction(()=>document.querySelector('#controller-phase')?.textContent==='ROUND COMPLETE');
  await host.screenshot({path:`${artifacts}public-results.png`});
  await phone.locator('#captain-action').click();
  await host.locator('#round-callout').waitFor({state:'visible',timeout:15000});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({url:base,hostedRoom:true,phoneFullscreen:await phone.evaluate(()=>!!document.fullscreenElement),transport:await phone.locator('#controller-connection').textContent(),fullThirtySecondRound:true,results:true,phoneRematch:true,errors},null,2));
  await phone.locator('#controller-menu').click();
  await phone.locator('#captain-lobby').click();
  await host.locator('#close-room-button').waitFor({state:'visible'});
  await host.locator('#close-room-button').click();
  await phone.locator('#join-view').waitFor({state:'visible',timeout:15000});
  console.log('Public room closed and controller returned to join page.');
} finally {await browser.close();}
